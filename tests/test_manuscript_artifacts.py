def _write_fixture_png(path: Path, mode: str) -> None:
    if mode == "corrupt":
        path.write_bytes(b"not a real png")
        return
    if mode == "blank":
        image = np.ones((480, 720, 3), dtype=float)
    else:
        x = np.linspace(0.05, 0.95, 720)
        y = np.linspace(0.15, 0.85, 480)
        xv, yv = np.meshgrid(x, y)
        image = np.dstack((xv, yv, 1.0 - xv * 0.65))
    mpimg.imsave(path, image)


