def _metric(**overrides: float) -> FigureImageMetrics:
    """A figure-image metric well above every threshold, with per-test overrides."""
    base: dict[str, float] = {
        "width": _MIN_FIGURE_WIDTH + 100,
        "height": _MIN_FIGURE_HEIGHT + 100,
        "channels": 3,
        "min_value": 0.0,
        "max_value": 1.0,
        "stddev": _MIN_FIGURE_STDDEV * 10,
        "bytes": 10_000,
    }
    base.update(overrides)
    return FigureImageMetrics(filename="probe.png", **base)  # type: ignore[arg-type]


def test_low_information_predicate_boundaries() -> None:
    """Pin the low-information gate's behavior exactly at each threshold.

    The predicate uses strict ``<``, so a metric sitting *exactly* on a threshold passes
    and a hair below fails. This guards the boundary so a future refactor cannot silently
    flip the comparison and start accepting (or rejecting) borderline figures.
    """
    assert not _is_low_information(_metric())

    # stddev: exactly the floor passes; just below is rejected as near-blank.
    assert not _is_low_information(_metric(stddev=_MIN_FIGURE_STDDEV))
    assert _is_low_information(_metric(stddev=_MIN_FIGURE_STDDEV - 1e-6))

    # value range: exactly the floor passes; a flatter span is rejected.
    assert not _is_low_information(_metric(min_value=0.0, max_value=_MIN_FIGURE_RANGE))
    assert _is_low_information(
        _metric(min_value=0.0, max_value=_MIN_FIGURE_RANGE - 1e-6)
    )

    # dimensions: exactly the minimum passes; one pixel under is rejected.
    assert not _is_low_information(
        _metric(width=_MIN_FIGURE_WIDTH, height=_MIN_FIGURE_HEIGHT)
    )
    assert _is_low_information(_metric(width=_MIN_FIGURE_WIDTH - 1))
    assert _is_low_information(_metric(height=_MIN_FIGURE_HEIGHT - 1))


