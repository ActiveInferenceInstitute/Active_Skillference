def test_figure_image_metrics_grayscale_image_reports_single_channel(
    tmp_path: Path,
) -> None:
    """A true 2-D (mode 'L') grayscale PNG is read as a single-channel metric.

    A PIL 'L' PNG round-trips through ``mpimg.imread`` as a genuine 2-D array, exercising
    the ``data.ndim == 2`` branch where ``channels`` is fixed to 1.
    """
    from PIL import Image

    arr = (np.linspace(0, 255, 480 * 640).reshape(480, 640)).astype("uint8")
    path = tmp_path / "gray.png"
    Image.fromarray(arr, mode="L").save(path)

    metric = _figure_image_metrics(path, "gray.png")

