#!/usr/bin/env python3
"""Write or check the measured gate-arm numbers in docs/gate_metrics.md.

Measured numbers are generated, never hand-edited: `./gates.sh record` times each
arm, writes the receipt to ``docs/_generated/arm_timings.json``, and renders this
document through the same script with ``--write``. The ``docs`` arm runs
``--check`` so a stale document fails the gate instead of publishing an old
measurement.

The receipt is the only place these numbers live. If you change an arm, re-record;
do not edit the Markdown or the JSON by hand.
"""

from __future__ import annotations

import argparse
import json
import platform
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "gate_metrics.md"
DEFAULT_TIMINGS = ROOT / "docs" / "_generated" / "arm_timings.json"
SCHEMA = "gate-arm-timings/v1"

# `pytest -q` prints "N passed, M skipped in 12.34s"; pytest-cov prints
# "Required test coverage of 90% reached. Total coverage: 97.23%". Both are stable
# CLI contracts; an unmatched line is an error, never a silently missing number.
PASSED_RE = re.compile(r"(\d+) passed")
SKIPPED_RE = re.compile(r"(\d+) skipped")
COVERAGE_RE = re.compile(r"Total coverage:\s*([\d.]+)%")


def _parse_test_log(text: str) -> dict[str, object]:
    passed = PASSED_RE.search(text)
    coverage = COVERAGE_RE.search(text)
    if passed is None or coverage is None:
        raise SystemExit(
            "could not read the test count and coverage from the recorded test arm; "
            "re-run ./gates.sh record"
        )
    skipped = SKIPPED_RE.search(text)
    return {
        "passed": int(passed.group(1)),
        "skipped": int(skipped.group(1)) if skipped else 0,
        "coverage_percent": coverage.group(1),
    }


def _rows(path: Path) -> list[dict[str, object]]:
    arms: list[dict[str, object]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        name, seconds, exit_code = line.split("\t")
        arms.append(
            {"arm": name, "seconds": round(float(seconds), 2), "exit": int(exit_code)}
        )
    if not arms:
        raise SystemExit(f"{path} recorded no arms")
    return arms


def build_receipt(rows: Path, test_log: Path) -> dict[str, object]:
    return {
        "schema": SCHEMA,
        "recorded": date.today().isoformat(),
        "platform": f"{platform.system()} {platform.machine()}",
        "arms": _rows(rows),
        "tests": _parse_test_log(
            test_log.read_text(encoding="utf-8", errors="replace")
        ),
    }


def render(receipt: dict[str, object]) -> str:
    arms = receipt["arms"]
    tests = receipt["tests"]
    assert isinstance(arms, list) and isinstance(tests, dict)
    total = sum(float(arm["seconds"]) for arm in arms)  # type: ignore[index]
    lines = [
        "# Gate metrics",
        "",
        "<!-- generated by scripts/z_generate_gate_metrics.py — do not hand-edit -->",
        "",
        "Measured on one host by `./gates.sh record`, which times each arm of",
        "[`gates.sh`](../gates.sh) and runs the full test arm once. `./gates.sh docs`",
        "fails when this file disagrees with the recorded receipt.",
        "",
        f"- Recorded: {receipt['recorded']}",
        f"- Platform: {receipt['platform']}",
        "- Receipt: [`docs/_generated/arm_timings.json`](_generated/arm_timings.json)",
        "",
        "Wall-clock time on a shared host. The uv and mypy caches are warm, so a first run",
        "on a fresh checkout is slower than the numbers below.",
        "",
        "## Wall time per arm",
        "",
        "| Arm | Seconds | Exit |",
        "| --- | --- | --- |",
    ]
    for arm in arms:
        lines.append(f"| `{arm['arm']}` | {arm['seconds']:.2f} | {arm['exit']} |")
    lines.extend(
        [
            f"| **sum of arms** | **{total:.2f}** | |",
            "",
            "`record` itself is excluded: it re-runs every arm above.",
            "",
            "## Test suite",
            "",
            "| Measure | Value |",
            "| --- | --- |",
            f"| Tests passed | {tests['passed']} |",
            f"| Tests skipped | {tests['skipped']} |",
            f"| `src/` coverage | {tests['coverage_percent']}% |",
            "",
            "The coverage floor is 90% and is enforced by `./gates.sh test`; the value",
            "above is what that arm reported on the recorded run.",
            "",
        ]
    )
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="record and render")
    parser.add_argument("--check", action="store_true", help="fail if the doc is stale")
    parser.add_argument(
        "--rows", type=Path, help="arm/seconds/exit rows from `gates.sh record`"
    )
    parser.add_argument("--test-log", type=Path, help="captured output of the test arm")
    parser.add_argument("--timings", type=Path, default=DEFAULT_TIMINGS)
    args = parser.parse_args(argv)
    args.timings = args.timings.resolve()

    if args.write:
        if args.rows is None or args.test_log is None:
            parser.error("--write needs --rows and --test-log (run ./gates.sh record)")
        receipt = build_receipt(args.rows, args.test_log)
        args.timings.parent.mkdir(parents=True, exist_ok=True)
        args.timings.write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")
        DOC.write_text(render(receipt), encoding="utf-8")
        print(f"wrote {DOC.relative_to(ROOT)} and {args.timings.relative_to(ROOT)}")
        return 0

    if args.check:
        if not args.timings.is_file():
            print(
                f"{args.timings.relative_to(ROOT)} is missing; run ./gates.sh record",
                file=sys.stderr,
            )
            return 1
        receipt = json.loads(args.timings.read_text(encoding="utf-8"))
        if receipt.get("schema") != SCHEMA:
            print(f"{args.timings} has an unexpected schema", file=sys.stderr)
            return 1
        if not DOC.is_file() or DOC.read_text(encoding="utf-8") != render(receipt):
            print(
                "docs/gate_metrics.md is stale versus docs/_generated/arm_timings.json; "
                "run ./gates.sh record",
                file=sys.stderr,
            )
            return 1
        print("gate metrics match the recorded receipt")
        return 0

    parser.print_help()
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
